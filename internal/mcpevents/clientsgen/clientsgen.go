// Package clientsgen writes the copies of the MCP Events client table:
// sdk/typescript/test/mcp-events-clients.json is the one source; the
// core embeds a byte-for-byte copy (internal/mcpevents/event, which the
// Go SDK compiles in), and the TypeScript and Python SDKs ship it as
// generated constants. `go generate ./internal/mcpevents/clientsgen`
// regenerates; the test fails if a copy drifts.
package clientsgen

//go:generate go run ./gen

import (
	"bytes"
	"encoding/json"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"strings"
)

// Source is the table, from the repository root.
const Source = "sdk/typescript/test/mcp-events-clients.json"

// Files returns every generated file, keyed by its path from the
// repository root.
func Files(root string) (map[string][]byte, error) {
	src, err := os.ReadFile(filepath.Join(root, Source))
	if err != nil {
		return nil, err
	}
	if !json.Valid(src) {
		return nil, fmt.Errorf("%s isn't valid JSON", Source)
	}
	data, err := Data(src)
	if err != nil {
		return nil, err
	}
	py, err := python(data)
	if err != nil {
		return nil, err
	}
	ts := "// Generated by `go generate ./internal/mcpevents/clientsgen` from " + Source + ". DO NOT EDIT.\n" +
		"// The MCP Events client table, which spec.ts evaluates, without its\n" +
		"// documentation (_about, reason, source, about: read them in the source) or what only Wakeshift reads (webhook_only).\n" +
		"// Internal: not exported from the package.\n\n" +
		"/** @internal */\nexport const CLIENT_TABLE = " + string(data) + ";\n"
	return map[string][]byte{
		"internal/mcpevents/event/mcp-events-clients.json": src,
		"sdk/typescript/src/clients.ts":                    []byte(ts),
		"sdk/python/src/wakeshift/_clients.py":             py,
	}, nil
}

// DocKeys are what the SDKs' generated copies leave out (keeping the
// TypeScript SDK's bundle small): the table's documentation, every key
// starting with _ and reason, source and about wherever they are; and
// webhook_only, which only the core reads (the unreachable-callback hint,
// internal/appapi/callbackhint.go).
func DocKeys(key string) bool {
	return strings.HasPrefix(key, "_") || key == "reason" || key == "source" || key == "about" || key == "webhook_only"
}

// Data is the table without its documentation (DocKeys), as compact JSON
// in the source's key order: what the SDKs ship.
func Data(src []byte) ([]byte, error) {
	dec := json.NewDecoder(bytes.NewReader(src))
	dec.UseNumber()
	var b bytes.Buffer
	if err := dataValue(&b, dec); err != nil {
		return nil, err
	}
	if _, err := dec.Token(); err != io.EOF {
		return nil, fmt.Errorf("%s: trailing data", Source)
	}
	return b.Bytes(), nil
}

func dataValue(b *bytes.Buffer, dec *json.Decoder) error {
	tok, err := dec.Token()
	if err != nil {
		return err
	}
	switch v := tok.(type) {
	case json.Delim:
		b.WriteByte(byte(v))
		first := true
		for dec.More() {
			if v == '{' {
				key, err := dec.Token()
				if err != nil {
					return err
				}
				if DocKeys(key.(string)) {
					var skip json.RawMessage
					if err := dec.Decode(&skip); err != nil {
						return err
					}
					continue
				}
				if !first {
					b.WriteByte(',')
				}
				b.WriteString(pyString(key.(string)) + ":")
			} else if !first {
				b.WriteByte(',')
			}
			first = false
			if err := dataValue(b, dec); err != nil {
				return err
			}
		}
		dec.Token()
		b.WriteString(map[json.Delim]string{'{': "}", '[': "]"}[v])
	case string:
		b.WriteString(pyString(v))
	case bool:
		b.WriteString(map[bool]string{true: "true", false: "false"}[v])
	case nil:
		b.WriteString("null")
	case json.Number:
		b.WriteString(v.String())
	}
	return nil
}

// python is the table as a Python module: one dict literal, laid out as
// ruff format keeps it (every collection expanded, with trailing commas).
func python(src []byte) ([]byte, error) {
	var b strings.Builder
	b.WriteString(`"""Generated by ` + "`go generate ./internal/mcpevents/clientsgen`" + ` from ` + Source + `. DO NOT EDIT.

The MCP Events client table, which _spec.py evaluates. Internal: not part of the package's API."""

from __future__ import annotations

from typing import Any, Final

CLIENT_TABLE: Final[dict[str, Any]] = `)
	dec := json.NewDecoder(bytes.NewReader(src))
	dec.UseNumber()
	if err := pyValue(&b, dec, 0); err != nil {
		return nil, err
	}
	if _, err := dec.Token(); err != io.EOF {
		return nil, fmt.Errorf("%s: trailing data", Source)
	}
	b.WriteString("\n")
	return []byte(b.String()), nil
}

// pyValue writes the next JSON value from dec as a Python literal,
// keeping key order.
func pyValue(b *strings.Builder, dec *json.Decoder, depth int) error {
	tok, err := dec.Token()
	if err != nil {
		return err
	}
	indent := func(d int) string { return strings.Repeat("    ", d) }
	switch v := tok.(type) {
	case json.Delim:
		closer := map[json.Delim]string{'{': "}", '[': "]"}[v]
		if !dec.More() {
			dec.Token()
			b.WriteString(string(v) + closer)
			return nil
		}
		b.WriteString(string(v) + "\n")
		for dec.More() {
			b.WriteString(indent(depth + 1))
			if v == '{' {
				key, err := dec.Token()
				if err != nil {
					return err
				}
				b.WriteString(pyString(key.(string)) + ": ")
			}
			if err := pyValue(b, dec, depth+1); err != nil {
				return err
			}
			b.WriteString(",\n")
		}
		dec.Token()
		b.WriteString(indent(depth) + closer)
	case string:
		b.WriteString(pyString(v))
	case bool:
		b.WriteString(map[bool]string{true: "True", false: "False"}[v])
	case nil:
		b.WriteString("None")
	case json.Number:
		b.WriteString(v.String())
	}
	return nil
}

// pyString is a double-quoted Python string literal: JSON's escapes are
// Python's too.
func pyString(s string) string {
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	enc.Encode(s)
	return strings.TrimRight(buf.String(), "\n")
}
